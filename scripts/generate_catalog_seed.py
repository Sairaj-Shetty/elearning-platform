def lesson(title, description, minutes=12, access="ENROLLED_ONLY", resources=None, sample_video=False):
    return {
        "title": title,
        "description": description,
        "minutes": minutes,
        "access": access,
        "resources": resources or [],
        "sampleVideo": sample_video,
    }


def section(title, description, lessons):
    return {"title": title, "description": description, "lessons": lessons}


